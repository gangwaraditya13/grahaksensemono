package com.adish.grahaksensemono.product.service.Impl;

import com.adish.grahaksensemono.product.Dto.S3.UploadUrlRequestDto;
import com.adish.grahaksensemono.product.Dto.S3.UploadUrlResponseDto;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import software.amazon.awssdk.core.ResponseBytes;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.*;
import software.amazon.awssdk.services.s3.presigner.S3Presigner;
import software.amazon.awssdk.services.s3.presigner.model.PresignedPutObjectRequest;
import software.amazon.awssdk.services.s3.presigner.model.PutObjectPresignRequest;

import java.time.Duration;
import java.util.Map;
import java.util.UUID;
import java.util.regex.Pattern;

@Service
public class S3FileService{

    private static final long MAX_SIZE = 2L * 1024 * 1024; // 2MB
    private static final String FOLDER = "products";
    private static final Map<String, String> ALLOWED = Map.of(
            "image/jpeg", "jpg",
            "image/png", "png",
            "image/webp", "webp"
    );
    // keys we generate ourselves: products/<uuid>.<ext>
    private static final Pattern KEY_PATTERN =
            Pattern.compile("^products/[0-9a-fA-F\\-]{36}\\.(jpg|png|webp)$");

    private final S3Client s3Client;
    private final S3Presigner presigner;

    @Value("${aws.s3.bucket-name}")
    private String bucket;

    @Value("${app.media.base-url}")
    private String baseUrl;

    @Value("${app.media.upload-url-minutes}")
    private long uploadUrlMinutes;

    public S3FileService(S3Client s3Client, S3Presigner presigner) {
        this.s3Client = s3Client;
        this.presigner = presigner;
    }

    //STEP 1: create signed upload URL
    public UploadUrlResponseDto createUploadUrl(UploadUrlRequestDto req) {
        String type = req.getContentType() == null ? "" : req.getContentType().toLowerCase();
        if (!ALLOWED.containsKey(type)) {
            throw new IllegalArgumentException("Only JPG, PNG or WEBP images are allowed");
        }
        if (req.getSize() <= 0 || req.getSize() > MAX_SIZE) {
            throw new IllegalArgumentException("Image must be 2MB or smaller");
        }

        // key is generated by the server, so the client cannot choose or overwrite paths
        String key = FOLDER + "/" + UUID.randomUUID() + "." + ALLOWED.get(type);

        PutObjectRequest put = PutObjectRequest.builder()
                .bucket(bucket)
                .key(key)
                .contentType(type)                    // signed: client must send the same type
                .contentLength(req.getSize())         // signed: client must send exactly this size
                .cacheControl("public, max-age=31536000")
                .build();

        PutObjectPresignRequest presignRequest = PutObjectPresignRequest.builder()
                .signatureDuration(Duration.ofMinutes(uploadUrlMinutes))
                .putObjectRequest(put)
                .build();

        PresignedPutObjectRequest presigned = presigner.presignPutObject(presignRequest);

        return new UploadUrlResponseDto(
                presigned.url().toString(),
                key,
                getUrl(key),
                (int) (uploadUrlMinutes * 60)
        );
    }

    //STEP 2: verify the upload really happened
    /** Call this when the product is saved. Throws if the key is invalid or the object is bad. */
    public String confirmUpload(String key) {
        if (key == null || !KEY_PATTERN.matcher(key).matches()) {
            throw new IllegalArgumentException("Invalid image key");
        }

        HeadObjectResponse head;
        try {
            head = s3Client.headObject(HeadObjectRequest.builder().bucket(bucket).key(key).build());
        } catch (NoSuchKeyException e) {
            throw new IllegalArgumentException("Image was not uploaded");
        }

        String type = String.valueOf(head.contentType()).toLowerCase();

        if (head.contentLength() > MAX_SIZE) {
            delete(key);
            throw new IllegalArgumentException("Image must be 2MB or smaller");
        }
        if (!ALLOWED.containsKey(type)) {
            delete(key);
            throw new IllegalArgumentException("Only JPG, PNG or WEBP images are allowed");
        }
        if (!hasValidSignature(key)) {
            delete(key);
            throw new IllegalArgumentException("File content is not a valid image");
        }
        return type;
    }

    //READ
    public String getUrl(String key) {
        if (key == null || key.isBlank()) return null;
        return baseUrl + "/" + key;
    }

    //UPDATE
    /** Client uploaded a new image with a fresh signed URL; verify it, then remove the old one. */
    public void replace(String oldKey, String newKey) {
        confirmUpload(newKey);
        if (oldKey != null && !oldKey.equals(newKey)) {
            delete(oldKey);
        }
    }

    //DELETE
    public void delete(String key) {
        if (key == null || key.isBlank()) return;
        s3Client.deleteObject(DeleteObjectRequest.builder().bucket(bucket).key(key).build());
    }

    //real image check (first 12 bytes)
    private boolean hasValidSignature(String key) {
        try {
            ResponseBytes<GetObjectResponse> bytes = s3Client.getObjectAsBytes(
                    GetObjectRequest.builder().bucket(bucket).key(key).range("bytes=0-11").build());
            byte[] h = bytes.asByteArray();
            if (h.length < 12) return false;

            boolean jpeg = (h[0] & 0xFF) == 0xFF && (h[1] & 0xFF) == 0xD8 && (h[2] & 0xFF) == 0xFF;
            boolean png = (h[0] & 0xFF) == 0x89 && h[1] == 'P' && h[2] == 'N' && h[3] == 'G';
            boolean webp = h[0] == 'R' && h[1] == 'I' && h[2] == 'F' && h[3] == 'F'
                    && h[8] == 'W' && h[9] == 'E' && h[10] == 'B' && h[11] == 'P';
            return jpeg || png || webp;
        } catch (Exception e) {
            return false;
        }
    }
}